    public IReadOnlyList<PromptTemplate> GetByCategory(string category)
    {
        return _templates.Where(t => t.Category == category).ToList();
    }

    public IReadOnlyList<string> GetCategories()
    {
        return _templates.Select(t => t.Category).Distinct().ToList();
    }

    public PromptTemplate Find(string category, string name)
    {
        return _templates.FirstOrDefault(t => t.Category == category && t.Name == name)
            ?? _templates.First(t => t.Category == category);
    }

    public void Save(PromptTemplate original, string name, string category, string content)
    {
        var index = _templates.FindIndex(t => t.Name == original.Name && t.Category == original.Category);
        var updated = new PromptTemplate(name.Trim(), category.Trim(), content, original.BuiltIn);
        if (index >= 0)
        {
            _templates[index] = updated;
        }
        else
        {
            _templates.Add(updated);
        }
    }

    public PromptTemplate Add(string name, string category, string content)
    {
        var template = new PromptTemplate(name.Trim(), category.Trim(), content.Trim(), false);
        _templates.Add(template);
        return template;
    }
